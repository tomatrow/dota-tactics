import type { Random } from "#lib/common/Random.ts"
import type { Targets } from "#lib/enums/Targets.ts"
import type { Unit } from "#lib/view-model-component/Unit.svelte.ts"
import type { BaseAbilityPicker } from "./ability-picker/BaseAbilityPicker.ts"
import { FixedAbilityPicker } from "./ability-picker/FixedAbilityPicker.ts"
import { RandomAbilityPicker } from "./ability-picker/RandomAbilityPicker.ts"
import { AttackPattern } from "./AttackPattern.ts"

/** A component as prefab data: its class name and its Inspector fields. */
type Component<T extends string, Fields = object> = { readonly type: T } & Readonly<Fields>

/** An ability picker. Pickers refer to others by the name of their GameObject. */
export type AbilityPickerPrefab =
	| Component<"FixedAbilityPicker", { target: Targets; ability: string }>
	| Component<"RandomAbilityPicker", { pickers: readonly string[] }>

/**
 * A `Resources/Attack Pattern/` prefab, generated by `scripts/convert-unity.ts`: an
 * `AttackPattern` (its `pickers`, by name) whose children each have an ability picker.
 */
export interface AttackPatternPrefab {
	readonly name: string
	readonly pickers: readonly string[]
	readonly children: readonly { readonly name: string; readonly picker: AbilityPickerPrefab }[]
}

/** Unity's `Instantiate(prefab)`, parented to `unit`: the unit's attack pattern. */
export function instantiateAttackPattern(
	prefab: AttackPatternPrefab,
	unit: Unit,
	{ random }: { readonly random: Random }
): AttackPattern {
	const pickers = new Map<string, BaseAbilityPicker>()
	for (const { name, picker } of prefab.children) {
		pickers.set(
			name,
			picker.type === "FixedAbilityPicker" ?
				new FixedAbilityPicker(unit, picker)
			:	new RandomAbilityPicker(unit, random)
		)
	}

	const find = (name: string): BaseAbilityPicker => {
		const picker = pickers.get(name)
		if (!picker) throw new Error(`No ability picker ${name} in ${prefab.name}`)
		return picker
	}
	// Once they all exist, as pickers may refer to any of them (even themselves).
	for (const { name, picker } of prefab.children) {
		if (picker.type === "RandomAbilityPicker")
			(find(name) as RandomAbilityPicker).pickers = picker.pickers.map(find)
	}
	return new AttackPattern(prefab.pickers.map(find))
}
