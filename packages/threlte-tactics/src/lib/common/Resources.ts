import type { AbilityCatalogRecipe } from "#lib/factory/AbilityCatalogRecipe.ts"
import type { UnitRecipe } from "#lib/factory/UnitRecipe.ts"
import type { ConversationData } from "#lib/model/ConversationData.ts"
import type { LevelData } from "#lib/model/LevelData.ts"
import type { AbilityPrefab } from "#lib/view-model-component/ability/AbilityPrefab.ts"
import type { JobPrefab } from "#lib/view-model-component/actor/Job.ts"
import type { AttackPatternPrefab } from "#lib/view-model-component/ai/AttackPatternPrefab.ts"

/** What each folder of `src/lib/resources/` holds. */
interface Folders {
	Abilities: AbilityPrefab
	"Ability Catalog Recipes": AbilityCatalogRecipe
	"Attack Pattern": AttackPatternPrefab
	Conversations: ConversationData
	Jobs: JobPrefab
	Levels: LevelData
	"Unit Recipes": UnitRecipe
}

export type ResourceFolder = keyof Folders

/** An asset's path: its folder, then its name (which may go through subfolders). */
export type ResourcePath = { [F in ResourceFolder]: `${F}/${string}` }[ResourceFolder]

/** The asset at `P`. */
export type Resource<P extends ResourcePath> =
	P extends `${infer F extends ResourceFolder}/${string}` ? Folders[F] : never

const modules = import.meta.glob<{ default: unknown }>("../resources/**/*.ts", { eager: true })

const prefix = "../resources/"

/** The game's data assets (`src/lib/resources/`, partly generated by `scripts/convert-unity.ts`). */
export const Resources = {
	/** The asset at `path` (no extension), or `null` if there is none. */
	load<P extends ResourcePath>(path: P): Resource<P> | null {
		const module = modules[`${prefix}${path}.ts`]
		return module ? (module.default as Resource<P>) : null
	},

	/** Every asset path in `folder`, sorted. */
	paths<F extends ResourceFolder>(folder: F): `${F}/${string}`[] {
		const start = `${prefix}${folder}/`
		return Object.keys(modules)
			.filter((key) => key.startsWith(start))
			.map((key) => key.slice(prefix.length, -".ts".length) as `${F}/${string}`)
			.sort()
	}
}
